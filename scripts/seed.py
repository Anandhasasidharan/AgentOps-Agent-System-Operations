"""Seed the AgentOps platform with demo data.

Usage:
    python scripts/seed.py

Prerequisites:
    docker compose up  (the five application services running)

Environment variables (all optional):
    CB_URL=http://localhost:8001
    CHAOS_URL=http://localhost:8002
    SLO_URL=http://localhost:8000
    API_KEY=dev-api-key
    AGENTOPS_ENV_FILE=.agentops.env   # where the seeded key is written

On success the script writes the tenant's real API key to ``.agentops.env``
(mode 0600) so the quickstart can load it with ``set -a; . ./.agentops.env``.
"""

import os
import shlex
import sys
import time
import uuid
from pathlib import Path

import httpx

CB_URL = os.getenv("CB_URL", "http://localhost:8001")
CHAOS_URL = os.getenv("CHAOS_URL", "http://localhost:8002")
SLO_URL = os.getenv("SLO_URL", "http://localhost:8000")
API_KEY = os.getenv("API_KEY", "dev-api-key")
GATEWAY_URL = os.getenv("GATEWAY_URL", "http://localhost:8004")

HEADERS = {"X-API-Key": API_KEY, "Content-Type": "application/json"}
PASS = "✓"
FAIL = "✗"

REQUEST_TIMEOUT = 10.0
# Chaos experiments run synchronously; give slow scenarios room to finish.
EXPERIMENT_TIMEOUT = 90.0
# Failure modes that block for tens of seconds are poor demo defaults.
BLOCKING_FAILURE_MODES = {"timeout", "slow_response"}

ENV_FILE = Path(
    os.getenv(
        "AGENTOPS_ENV_FILE",
        str(Path(__file__).resolve().parent.parent / ".agentops.env"),
    )
)


def wait_for(url: str, name: str, retries: int = 30, delay: float = 1.0) -> bool:
    for i in range(retries):
        try:
            r = httpx.get(f"{url}/health", timeout=3)
            if r.status_code == 200:
                print(f"  {PASS} {name} ready ({url})")
                return True
        except httpx.RequestError:
            pass
        time.sleep(delay)
    print(f"  {FAIL} {name} not ready after {retries * delay}s ({url})")
    return False


def post(
    url: str,
    json: dict | None = None,
    headers: dict | None = None,
    timeout: float = REQUEST_TIMEOUT,
) -> httpx.Response:
    h = headers or HEADERS
    return httpx.post(url, json=json, headers=h, timeout=timeout)


def get(
    url: str,
    headers: dict | None = None,
    timeout: float = REQUEST_TIMEOUT,
) -> httpx.Response:
    return httpx.get(url, headers=headers or HEADERS, timeout=timeout)


def write_env_file(api_key: str) -> Path:
    """Persist the seeded key where the README quickstart can source it."""
    ENV_FILE.write_text(
        "# Generated by scripts/seed.py — local demo credentials\n"
        f"API_KEY={shlex.quote(api_key)}\n"
    )
    ENV_FILE.chmod(0o600)
    return ENV_FILE


def main() -> int:
    global API_KEY
    print("\n=== AgentOps — Seed Demo Data ===\n")

    # 1. Wait for all services
    print("Waiting for services...")
    ok = all(
        [
            wait_for(SLO_URL, "SLO Platform"),
            wait_for(CB_URL, "Circuit Breaker"),
            wait_for(CHAOS_URL, "Chaos Toolkit"),
        ]
    )
    if not ok:
        print(f"\n{FAIL} Some services not available. Is `docker compose up` running?")
        return 1
    print()

    # 2. Create tenant (unauthenticated)
    print("Creating tenant...")
    slug = API_KEY.split(":", 1)[0]
    r = post(
        f"{SLO_URL}/api/v1/tenants",
        json={"slug": slug, "name": "Acme Corp"},
        headers={"Content-Type": "application/json"},
    )
    if r.status_code == 201:
        data = r.json()
        api_key = data.get("api_key")
        if not api_key:
            print(f"  {FAIL} Create tenant: response did not include an API key")
            return 1
        API_KEY = api_key
        HEADERS["X-API-Key"] = API_KEY
        print(f"  {PASS} Tenant '{slug}' created")
    elif r.status_code == 409:
        if ":" not in API_KEY:
            print(f"  {FAIL} Tenant '{slug}' already exists, but no API key was supplied.")
            print(
                "       Re-run with API_KEY='<slug>:<token>', or remove the Postgres\n"
                "       volume so the seed can create a fresh tenant."
            )
            return 1
        print(f"  {PASS} Tenant '{slug}' already exists (using supplied API key)")
    else:
        print(f"  {FAIL} Create tenant: {r.status_code} {r.text[:200]}")
        return 1

    # 3. Create agent
    print("Creating agent...")
    r = post(
        f"{SLO_URL}/api/v1/agents",
        json={
            "name": "demo-agent",
            "environment": "production",
            "framework": "langchain",
            "model_provider": "openai",
        },
    )
    if r.status_code in (200, 201):
        agent = r.json()
        print(f"  {PASS} Agent 'demo-agent' created (id={agent['id']})")
    else:
        print(f"  {FAIL} Create agent: {r.status_code} {r.text[:200]}")
        return 1

    # 4. Create SLI
    print("Creating SLI...")
    r = post(
        f"{SLO_URL}/api/v1/slis",
        json={
            "name": "task-success-rate",
            "metric_type": "ratio",
            "source": "otel",
            "config": {},
        },
    )
    if r.status_code in (200, 201):
        sli = r.json()
        print(f"  {PASS} SLI 'task-success-rate' created (id={sli['id']})")
    else:
        print(f"  {FAIL} Create SLI: {r.status_code} {r.text[:200]}")
        return 1

    # 5. Create SLO
    print("Creating SLO...")
    r = post(
        f"{SLO_URL}/api/v1/slos",
        json={
            "sli_id": str(sli["id"]),
            "name": "95% task success (30d rolling)",
            "description": (
                "Demo SLO: agents must complete 95% of tasks successfully "
                "over a 30-day rolling window"
            ),
            "target": 0.95,
            "comparator": "gt",
            "window": "30d",
            "labels": {"env": "production", "team": "platform"},
        },
    )
    if r.status_code in (200, 201):
        slo = r.json()
        print(f"  {PASS} SLO created (id={slo['id']}, target=95%)")
    else:
        print(f"  {FAIL} Create SLO: {r.status_code} {r.text[:200]}")
        return 1

    # 6. Seed chaos scenarios
    print("Seeding chaos scenarios...")
    r = post(f"{CHAOS_URL}/api/v1/scenarios/seed")
    if r.status_code == 200:
        count = len(r.json())
        print(f"  {PASS} {count} built-in chaos scenarios seeded")
    elif r.status_code == 409:
        print(f"  {PASS} Chaos scenarios already seeded")
    else:
        print(f"  ({r.status_code}) {r.text[:200]}")

    # 7. Pick a fast scenario for the demo experiment
    print("Fetching chaos scenarios...")
    r = get(f"{CHAOS_URL}/api/v1/scenarios")
    scenarios = r.json() if r.status_code == 200 else []
    scenario = next(
        (s for s in scenarios if s.get("failure_mode") not in BLOCKING_FAILURE_MODES),
        scenarios[0] if scenarios else None,
    )
    if scenario:
        scenario_id = scenario["id"]
        print(f"  {PASS} Using scenario '{scenario['name']}' ({scenario_id})")
    else:
        print(f"  {FAIL} No scenarios available")
        scenario_id = None

    # 8. Run a chaos experiment
    if scenario_id:
        print("Running chaos experiment...")
        r = post(
            f"{CHAOS_URL}/api/v1/experiments",
            json={
                "scenario_id": str(scenario_id),
                "agent_id": "demo-agent",
            },
            timeout=EXPERIMENT_TIMEOUT,
        )
        if r.status_code in (200, 201):
            exp = r.json()
            print(
                f"  {PASS} Experiment started (id={exp['id']}, "
                f"status={exp.get('status', 'running')})"
            )
        else:
            print(f"  {FAIL} Run experiment: {r.status_code} {r.text[:200]}")
            return 1

    # 9. Create a policy (block dangerous commands)
    print("Creating circuit breaker policy...")
    r = post(
        f"{CB_URL}/api/v1/policies",
        json={
            "name": "block-dangerous-commands",
            "description": "Block filesystem-destructive tools from running",
            "enabled": True,
            "priority": 100,
            "policy_type": "tool_blocklist",
            "conditions": {
                "tools": ["rm", "rmdir", "dd", "mkfs", "shutdown", "reboot", "kill", "pkill"],
            },
            "action": "block",
            "action_config": {"reason": "Dangerous filesystem command blocked by policy"},
        },
    )
    if r.status_code in (200, 201):
        policy = r.json()
        print(f"  {PASS} Policy 'block-dangerous-commands' created (id={policy['id']})")
    elif r.status_code == 409:
        print(f"  {PASS} Policy already exists")
    else:
        print(f"  {FAIL} Create policy: {r.status_code} {r.text[:200]}")
        return 1

    # 10. Send safe tool call via circuit breaker
    print("Sending safe tool call...")
    r = post(
        f"{CB_URL}/v1/intercept",
        json={
            "agent_id": "demo-agent",
            "session_id": f"session-{uuid.uuid4().hex[:8]}",
            "tool_name": "read_file",
            "tool_input": {"path": "/tmp/test.txt"},
            "tool_output": {"content": "hello world", "size_bytes": 11},
            "duration_ms": 150.0,
            "token_count": 50,
        },
    )
    if r.status_code == 200:
        result = r.json()
        decision = result.get("decision", "unknown")
        print(f"  {PASS} Safe tool call -> {decision}")
    else:
        print(f"  ({r.status_code}) read_file: {r.text[:200]}")

    # 11. Send blocked tool call
    print("Sending blocked tool call...")
    r = post(
        f"{CB_URL}/v1/intercept",
        json={
            "agent_id": "demo-agent",
            "session_id": f"session-{uuid.uuid4().hex[:8]}",
            "tool_name": "rm",
            "tool_input": {"path": "/", "recursive": True, "force": True},
            "duration_ms": 0.5,
            "token_count": 10,
        },
    )
    if r.status_code == 200:
        result = r.json()
        decision = result.get("decision", "unknown")
        print(f"  {PASS} Blocked tool call -> {decision}")
    else:
        print(f"  ({r.status_code}) rm: {r.text[:200]}")

    # 12. Send OTel trace span to SLO
    print("Sending OTel trace span...")
    trace_id = uuid.uuid4().hex
    span_id = uuid.uuid4().hex[:16]
    r = post(
        f"{SLO_URL}/v1/traces",
        json={
            "resourceSpans": [
                {
                    "resource": {
                        "attributes": [
                            {"key": "service.name", "value": {"stringValue": "demo-agent"}},
                            {"key": "agentops.agent.id", "value": {"stringValue": "demo-agent"}},
                            {
                                "key": "agentops.environment",
                                "value": {"stringValue": "production"},
                            },
                        ]
                    },
                    "scopeSpans": [
                        {
                            "spans": [
                                {
                                    "traceId": trace_id,
                                    "spanId": span_id,
                                    "name": "task-execution",
                                    "kind": 2,
                                    "startTimeUnixNano": str(int(time.time() * 1_000_000_000)),
                                    "endTimeUnixNano": str(
                                        int(time.time() * 1_000_000_000) + 150_000_000
                                    ),
                                    "attributes": [
                                        {
                                            "key": "gen_ai.eval.success",
                                            "value": {"intValue": "1"},
                                        },
                                        {
                                            "key": "gen_ai.eval.total",
                                            "value": {"intValue": "1"},
                                        },
                                        {
                                            "key": "gen_ai.tool.success",
                                            "value": {"intValue": "1"},
                                        },
                                        {
                                            "key": "gen_ai.tool.calls",
                                            "value": {"intValue": "1"},
                                        },
                                        {
                                            "key": "gen_ai.usage.input_tokens",
                                            "value": {"intValue": "450"},
                                        },
                                        {
                                            "key": "gen_ai.usage.output_tokens",
                                            "value": {"intValue": "120"},
                                        },
                                        {
                                            "key": "gen_ai.response.duration",
                                            "value": {"intValue": "150"},
                                        },
                                    ],
                                    "status": {"code": 1},
                                }
                            ]
                        }
                    ],
                }
            ]
        },
    )
    if r.status_code in (200, 202):
        print(f"  {PASS} OTel span ingested by SLO")
    else:
        print(f"  ({r.status_code}) OTel: {r.text[:200]}")

    # Summary
    env_path = write_env_file(API_KEY)
    print(f"\n{'=' * 50}")
    print(f"  {PASS} Seed complete!")
    print("\n  Dashboard: http://localhost:8003")
    print(f"  API Key:   {API_KEY}")
    print(f"  Env file:  {env_path} (mode 600)")
    print(f"\n  Load it:   set -a; . {env_path}; set +a")
    print("\n  Try these CLIs:")
    print('    cbctl    status demo-agent --api-key "$API_KEY"')
    print('    chaosctl report --api-key "$API_KEY"')
    print('    sloctl   status --api-key "$API_KEY"')
    print(f"{'=' * 50}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
